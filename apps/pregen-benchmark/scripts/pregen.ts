/**
 * Build-time shader generation for the `pregen` variants.
 *
 * For every `examples/<name>/pregen/shaders.ts`, loads the module in Node
 * (through Vite, so that `unplugin-typegpu` processes 'use gpu' functions),
 * calls `tgpu.resolve` on every exported shader module and writes the WGSL
 * into `examples/<name>/pregen/generated.ts` as plain string constants.
 *
 * The browser bundle of a `pregen` variant then never imports TypeGPU.
 */
import { existsSync, readdirSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import typegpu from 'unplugin-typegpu/vite';
import { createServer } from 'vite';

const examplesDir = fileURLToPath(new URL('../examples/', import.meta.url));
const only = process.argv[2];

const server = await createServer({
  configFile: false,
  root: fileURLToPath(new URL('..', import.meta.url)),
  plugins: [typegpu({})],
  server: { middlewareMode: true, hmr: false, ws: false },
  appType: 'custom',
  logLevel: 'warn',
});

try {
  const { tgpu } = (await server.ssrLoadModule('typegpu')) as typeof import('typegpu');

  for (const example of readdirSync(examplesDir)) {
    if (only && example !== only) {
      continue;
    }
    const shadersPath = `${examplesDir}${example}/pregen/shaders.ts`;
    if (!existsSync(shadersPath)) {
      continue;
    }

    const { shaderModules } = (await server.ssrLoadModule(shadersPath)) as {
      shaderModules: Record<string, Parameters<typeof tgpu.resolve>[0]>;
    };

    let output = '// Generated by scripts/pregen.ts with tgpu.resolve, do not edit.\n';
    for (const [name, items] of Object.entries(shaderModules)) {
      const code = Array.isArray(items) ? tgpu.resolve(items) : tgpu.resolve(items);
      output += `\nexport const ${name} = ${JSON.stringify(code)};\n`;
    }
    writeFileSync(`${examplesDir}${example}/pregen/generated.ts`, output);
    console.log(
      `Pregenerated ${Object.keys(shaderModules).length} shader module(s) for ${example}`,
    );
  }
} finally {
  await server.close();
}
